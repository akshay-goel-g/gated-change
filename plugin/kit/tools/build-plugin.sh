#!/usr/bin/env bash
#
# build-plugin.sh — assemble plugin/kit/ from the repository's portable kit files.
#
# WHY. The repository root also holds this project's own ledger, dashboard, tests and
# history. A Claude Code plugin installs a COPY of its folder, so what a user receives must
# be the kit alone. plugin/.claude-plugin/ and plugin/skills/ are written by hand; plugin/kit/
# is generated here from the sources, and tests/run.sh fails if it has drifted.
#
# Usage:
#   bash tools/build-plugin.sh                # rebuild plugin/kit/ in place
#   bash tools/build-plugin.sh <plugin-dir>   # build <plugin-dir>/kit/ elsewhere (the test uses this)
#
# It also copies LICENSE and NOTICE to the plugin root, where the directory expects them.
#
# Exit: 0 built; 1 a source is missing or the target could not be written.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
PLUGIN="${1:-$ROOT/plugin}"
OUT="$PLUGIN/kit"

DIRS="core tools templates examples"
FILES="README.md VERSION LICENSE NOTICE CHANGELOG.md"

for d in $DIRS; do
  [ -d "$ROOT/$d" ] || { echo "build-plugin: missing directory $ROOT/$d" >&2; exit 1; }
done
for f in $FILES; do
  [ -f "$ROOT/$f" ] || { echo "build-plugin: missing file $ROOT/$f" >&2; exit 1; }
done

# Refuse to delete something that is not a previous build: a mistyped argument must not
# wipe a directory that holds other work.
if [ -e "$OUT" ] && [ ! -f "$OUT/.built-by-build-plugin" ]; then
  if [ -n "$(ls -A "$OUT" 2>/dev/null)" ]; then
    echo "build-plugin: $OUT exists and is not a previous build; refusing to replace it" >&2
    exit 1
  fi
fi

rm -rf "$OUT"
mkdir -p "$OUT"
cp "$ROOT/LICENSE" "$ROOT/NOTICE" "$PLUGIN/"
for d in $DIRS; do cp -R "$ROOT/$d" "$OUT/$d"; done
for f in $FILES; do cp "$ROOT/$f" "$OUT/$f"; done
printf 'generated by tools/build-plugin.sh; do not edit\n' > "$OUT/.built-by-build-plugin"

echo "built $OUT ($(find "$OUT" -type f | wc -l | tr -d ' ') files)"
